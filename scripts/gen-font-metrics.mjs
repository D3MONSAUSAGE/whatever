// Generates lib/board-font-metrics.ts: advance widths (per 1000 em) of every bundled board face, measured with
// @napi-rs/canvas from the same TTF files resvg draws with. The premium menu templates lay out text from these
// numbers in shared code, so the browser preview and the server PNG wrap and size text identically.
// Run: node scripts/gen-font-metrics.mjs
import { createCanvas, GlobalFonts } from "@napi-rs/canvas";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const faces = [
  ["Inter", 400, "Inter-Regular.ttf"], ["Inter", 700, "Inter-Bold.ttf"], ["Inter", 800, "Inter-ExtraBold.ttf"],
  ["Noto Serif", 400, "NotoSerif-Regular.ttf"], ["Noto Serif", 700, "NotoSerif-Bold.ttf"],
  ["Montserrat", 400, "Montserrat-Regular.ttf"], ["Montserrat", 700, "Montserrat-Bold.ttf"], ["Montserrat", 800, "Montserrat-ExtraBold.ttf"],
  ["Oswald", 400, "Oswald-Regular.ttf"], ["Oswald", 700, "Oswald-Bold.ttf"],
  ["Bebas Neue", 400, "BebasNeue-Regular.ttf"], ["Lobster", 400, "Lobster-Regular.ttf"],
  ["Cormorant Garamond", 500, "CormorantGaramond-Medium.ttf"], ["Cormorant Garamond", 600, "CormorantGaramond-SemiBold.ttf"],
  ["Cormorant Garamond", 700, "CormorantGaramond-Bold.ttf"], ["Cormorant Garamond", 500, "CormorantGaramond-MediumItalic.ttf", "i"],
  ["Playfair Display", 400, "PlayfairDisplay-Regular.ttf"], ["Playfair Display", 700, "PlayfairDisplay-Bold.ttf"],
  ["Playfair Display", 400, "PlayfairDisplay-Italic.ttf", "i"],
];
const chars = [];
for (let c = 32; c < 127; c++) chars.push(String.fromCharCode(c));
for (let c = 160; c < 256; c++) chars.push(String.fromCharCode(c));
chars.push(..."‘’“”–—•…€™");
const out = {};
// Italic faces are keyed "Family|weight|i"; upright keys are unchanged.
for (const [family, weight, file, style] of faces) {
  const alias = `M_${file.replace(/\W/g, "")}`;
  GlobalFonts.registerFromPath(join("assets/fonts", file), alias);
  const ctx = createCanvas(10, 10).getContext("2d");
  ctx.font = `1000px ${alias}`;
  const widths = {};
  for (const ch of chars) widths[ch] = Math.round(ctx.measureText(ch).width);
  out[style ? `${family}|${weight}|${style}` : `${family}|${weight}`] = widths;
}
const body = `/* Generated by scripts/gen-font-metrics.mjs from assets/fonts. Advance widths per 1000 em. Do not edit. */\n` +
  `export const FONT_METRICS: Record<string, Record<string, number>> = ${JSON.stringify(out)};\n`;
writeFileSync("lib/board-font-metrics.ts", body);
console.log(Object.keys(out).length, "faces,", chars.length, "chars");
